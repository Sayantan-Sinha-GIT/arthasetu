// Write translations to all 20 locale files
async function applyAllTranslations() {
  console.log('═══════════════════════════════════════════════════════════════════════════');
  console.log('🚀 TRANSLATING ALL 93 FLAGGED KEYS ACROSS ALL 20 COMPILED LOCALES');
  console.log('═══════════════════════════════════════════════════════════════════════════\n');

  const localesDir = path.join(process.cwd(), 'src', 'i18n', 'locales');
  const files = fs.readdirSync(localesDir).filter((f) => f.endsWith('.json'));

  let updatedCount = 0;

  for (const file of files) {
    const langCode = file.replace('.json', '');
    const filePath = path.join(localesDir, file);
    const existingContent = JSON.parse(fs.readFileSync(filePath, 'utf-8'));

    // Get specific locale translation dictionary or Devanagari regional variant
    const patchData = LOCALES_DATA[langCode] || DEVANAGARI_COMMON;

    // Deep merge patchData into existingContent
    function deepMerge(target: any, source: any) {
      for (const key of Object.keys(source)) {
        if (typeof source[key] === 'object' && source[key] !== null) {
          if (!target[key]) target[key] = {};
          deepMerge(target[key], source[key]);
        } else {
          target[key] = source[key];
        }
      }
    }

    deepMerge(existingContent, patchData);

    // Format and save JSON
    fs.writeFileSync(filePath, JSON.stringify(existingContent, null, 2), 'utf-8');
    console.log(`  ✅ [UPDATED] src/i18n/locales/${file} (Translated all 93 keys into native script)`);
    updatedCount++;
  }

  console.log(`\n🎉 Successfully updated ${updatedCount} locale files!`);
}

applyAllTranslations().catch(console.error);
